// FNV-1a — ให้ข้อความคงที่ทั้งวันต่อคน
function hashStr(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/**
 * เลือกข้อความต้อนรับ
 * @param daysSince วันตั้งแต่ทำข้อสอบล่าสุด (0=วันนี้, null=ไม่เคยทำเลย)
 */
export function pickGreeting(uid: string, dateStr: string, daysSince: number | null): Greeting {
  const tone: GreetTone =
    daysSince === null ? "new"
    : daysSince <= 0   ? "praise"
    : daysSince <= 2   ? "welcome"
    : daysSince <= 6   ? "nudge"
    :                    "scold";
  const pool = POOLS[tone];
  const text = pool.texts[hashStr(`${dateStr}:${uid}`) % pool.texts.length]
    .replace("{d}", String(daysSince ?? 0));
  return { tone, emoji: pool.emoji, text };
}
